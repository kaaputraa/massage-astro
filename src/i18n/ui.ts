export type UiKey = Keys;

export function useT(lang: Lang) {
  const dict = ui[lang] as Record<string, string>;
  const fallback = ui.id as Record<string, string>;

  return (key: UiKey, vars: Record<string, string> = {}) => {
    const raw = dict[key] ?? fallback[key];
    if (raw === undefined) {
      console.warn(`[i18n] Kunci hilang: "${key}" (bahasa: ${lang})`);
      return key;
    }
    return Object.entries(vars).reduce(
      (text, [k, v]) => text.replaceAll(`{${k}}`, v),
      raw,
    );
  };
}

